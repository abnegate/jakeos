pub fn is_none(value: &str) -> bool {
    let trimmed = value.trim();
    trimmed.is_empty() || trimmed == "none"
}

pub fn display_list(values: &[String]) -> String {
    if values.is_empty() {
        "none".to_string()
    } else {
        values.join(", ")
    }
}

pub fn is_ident_char(character: char) -> bool {
    character.is_ascii_alphanumeric() || character == '-' || character == '@'
}

pub fn replace_identifier(text: &str, from: &str, to: &str) -> String {
    if from.is_empty() || from == to {
        return text.to_string();
    }
    let mut output = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(position) = rest.find(from) {
        let before = &rest[..position];
        let after_index = position + from.len();
        let after = &rest[after_index..];
        let left = before
            .chars()
            .last()
            .map(|character| !is_ident_char(character))
            .unwrap_or(true);
        let right = after
            .chars()
            .next()
            .map(|character| !is_ident_char(character))
            .unwrap_or(true);
        output.push_str(before);
        if left && right {
            output.push_str(to);
        } else {
            output.push_str(from);
        }
        rest = after;
    }
    output.push_str(rest);
    output
}

pub fn apply_replacements(text: &str, mapping: &[(String, String)]) -> String {
    let mut output = text.to_string();
    for (from, to) in mapping {
        output = replace_identifier(&output, from, to);
    }
    output
}

pub fn apply_glossary(title: &str, terms: &[String]) -> String {
    let mut output = title.to_string();
    for term in terms {
        if term.is_empty() {
            continue;
        }
        let mut rebuilt = String::with_capacity(output.len());
        let mut rest = output.as_str();
        let lower_term = term.to_ascii_lowercase();
        while !rest.is_empty() {
            let lower_rest = rest.to_ascii_lowercase();
            let Some(position) = lower_rest.find(&lower_term) else {
                rebuilt.push_str(rest);
                break;
            };
            let (before, matched_and_after) = rest.split_at(position);
            let (_, after) = matched_and_after.split_at(term.len());
            let left = before
                .chars()
                .last()
                .map(|character| !character.is_ascii_alphanumeric())
                .unwrap_or(true);
            let right = after
                .chars()
                .next()
                .map(|character| !character.is_ascii_alphanumeric())
                .unwrap_or(true);
            rebuilt.push_str(before);
            if left && right {
                rebuilt.push_str(term);
            } else {
                rebuilt.push_str(&matched_and_after[..term.len()]);
            }
            rest = after;
        }
        output = rebuilt;
    }
    output
}

pub fn family_of<'a>(patterns: &'a Patterns, identifier: &str) -> Option<&'a str> {
    [
        "DRAFT", "TASK", "D", "R", "B", "C", "T", "I", "Q", "H", "S", "GATE", "DEMO",
    ]
    .into_iter()
    .find(|name| patterns.matches_family(name, identifier))
}

pub fn markdown_files(directory: &Path) -> Vec<PathBuf> {
    let Ok(entries) = std::fs::read_dir(directory) else {
        return Vec::new();
    };
    let mut files: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "md"))
        .collect();
    files.sort();
    files
}

pub fn walk_markdown(directory: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    let mut stack = vec![directory.to_path_buf()];
    while let Some(current) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&current) else {
            continue;
        };
        for entry in entries.filter_map(|entry| entry.ok()) {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|extension| extension == "md") {
                files.push(path);
            }
        }
    }
    files.sort();
    files
}

pub fn ensure_trailing_newline(text: &str) -> String {
    let mut output = text.to_string();
    if !output.ends_with('\n') {
        output.push('\n');
    }
    output
}

pub fn next_number(numbers: impl Iterator<Item = u32>) -> u32 {
    numbers.max().unwrap_or(0) + 1
}

pub fn format_task_id(prefix: &str, number: u32) -> String {
    format!("{prefix}-{number:03}")
}

