pub fn first_word(title: &str) -> &str {
    title
        .split(|character: char| character.is_whitespace() || character == '/' || character == ':')
        .find(|word| !word.is_empty())
        .unwrap_or(title)
}

pub fn is_imperative_title(title: &str) -> bool {
    let word = first_word(title);
    if IMPERATIVE_VERBS
        .iter()
        .any(|verb| verb.eq_ignore_ascii_case(word))
    {
        return true;
    }
    let lower = word.to_ascii_lowercase();
    let article = matches!(lower.as_str(), "the" | "a" | "an" | "this" | "that");
    let plural_or_gerund =
        (lower.ends_with('s') && !lower.ends_with("ss")) || lower.ends_with("ing");
    let capitalised = word
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_uppercase());
    capitalised && !article && !plural_or_gerund
}

pub fn strip_generated_text(content: &str) -> String {
    let mut output = String::new();
    let mut inside = false;
    for line in content.lines() {
        if crate::parser::is_marker_begin(line) {
            inside = true;
            continue;
        }
        if crate::parser::is_marker_end(line) {
            inside = false;
            continue;
        }
        if !inside {
            output.push_str(line);
            output.push('\n');
        }
    }
    output
}

pub fn copy_dir(from: &Path, to: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(to)?;
    for entry in std::fs::read_dir(from)? {
        let entry = entry?;
        let destination = to.join(entry.file_name());
        if entry.path().is_dir() {
            copy_dir(&entry.path(), &destination)?;
        } else {
            std::fs::copy(entry.path(), destination)?;
        }
    }
    Ok(())
}

pub fn matrix_entries(text: &str) -> Vec<String> {
    let pattern =
        regex::Regex::new(r"\b(qemu-[a-z0-9_-]+|hw-h\d{3})\b").expect("matrix entry pattern");
    pattern
        .find_iter(text)
        .map(|found| found.as_str().to_string())
        .collect()
}

